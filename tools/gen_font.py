#!/usr/bin/env python3
"""
Generates src/ufont_data.cpp: anti-aliased (4-bit) UTF-8/Unicode bitmap fonts for the UI.

  pip install pillow fonttools
  python tools/gen_font.py [regular.ttf] [bold.ttf]

Default fonts: Liberation Sans (SIL Open Font License 1.1). Any TTF with the glyphs you need works.
Edit RANGES to add more scripts (e.g. Greek 0x370-0x3FF); each glyph costs roughly 40-100 bytes of flash.
"""
import sys
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

REG  = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf"
BOLD = sys.argv[2] if len(sys.argv) > 2 else "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"

# (name, ttf, pixel size)
FONTS = [("small", REG, 17), ("bold", BOLD, 23)]

RANGES = [
    (0x20, 0x7E),      # ASCII
    (0xA0, 0xFF),      # Latin-1 supplement
    (0x100, 0x17F),    # Latin Extended-A
    (0x400, 0x4FF),    # Cyrillic (Russian, Ukrainian, Belarusian, Serbian, Bulgarian, ...)
    (0x2010, 0x2015), (0x2018, 0x201E), (0x2022, 0x2022), (0x2026, 0x2026),
    (0x2030, 0x2030), (0x2039, 0x203A), (0x20AC, 0x20AC), (0x2116, 0x2116), (0x2122, 0x2122),
]

def build(name, path, size):
    cmap = TTFont(path, fontNumber=0).getBestCmap()
    font = ImageFont.truetype(path, size)
    glyphs, bmp = [], bytearray()
    W = H = size * 3
    base_x, base_y = size, size * 2
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            if cp not in cmap:
                continue
            ch = chr(cp)
            adv = int(round(font.getlength(ch)))
            img = Image.new("L", (W, H), 0)
            ImageDraw.Draw(img).text((base_x, base_y), ch, font=font, fill=255, anchor="ls")
            bbox = img.getbbox()
            if bbox is None:                      # space / invisible
                glyphs.append((cp, len(bmp), 0, 0, adv, 0, 0))
                continue
            l, t, r, b = bbox
            w, h = r - l, b - t
            px = img.crop(bbox).load()
            nib = []
            for y in range(h):
                for x in range(w):
                    nib.append((px[x, y] * 15 + 127) // 255)
            if len(nib) & 1:
                nib.append(0)
            off = len(bmp)
            for i in range(0, len(nib), 2):
                bmp.append((nib[i] << 4) | nib[i + 1])
            glyphs.append((cp, off, w, h, adv, l - base_x, t - base_y))
    asc, desc = font.getmetrics()
    return glyphs, bmp, int(round((asc + desc) * 1.02)), asc

def emit(f, name, glyphs, bmp, yadv, asc):
    f.write(f"static const uint8_t bmp_{name}[] = {{\n")
    for i in range(0, len(bmp), 24):
        f.write("  " + ",".join(f"0x{b:02X}" for b in bmp[i:i+24]) + ",\n")
    f.write("};\n")
    f.write(f"static const UGlyph glyphs_{name}[] = {{\n")
    for cp, off, w, h, adv, xo, yo in glyphs:
        f.write(f"  {{0x{cp:04X},{off},{w},{h},{adv},{xo},{yo}}},\n")
    f.write("};\n")
    f.write(f"const UFont UF_{name.upper()} = {{bmp_{name}, glyphs_{name}, {len(glyphs)}, {yadv}, {asc}}};\n\n")

with open("src/ufont_data.cpp", "w") as f:
    f.write("// GENERATED by tools/gen_font.py - do not edit.\n"
            "// Glyphs from Liberation Sans (SIL Open Font License 1.1).\n"
            '#include "ufont.h"\n\n')
    for name, path, size in FONTS:
        g, b, ya, asc = build(name, path, size)
        print(f"{name}: {len(g)} glyphs, {len(b)} bytes bitmap, lineheight {ya}")
        emit(f, name, g, b, ya, asc)
